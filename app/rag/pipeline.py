from pathlib import Path
import json
import re

from app.retrieval.vector_store import VectorStore
from app.rag.generator import LocalGenerator
from app.rag.citations import build_citations


ABSTAIN_MESSAGE = (
    "I couldn't find sufficient evidence in the indexed documents "
    "to answer this question."
)


FINANCIAL_TERMS = (
    "revenue",
    "income",
    "profit",
    "loss",
    "earnings",
    "expense",
    "expenses",
    "assets",
    "liabilities",
    "liability",
    "equity",
    "cash flow",
    "cashflow",
    "cash",
    "debt",
    "ratio",
    "ratios",
    "turnover",
    "financial",
    "balance sheet",
    "profit and loss",
    "statement of profit",
    "statement of income",
)


class RAGPipeline:

    def __init__(
        self,
        index_dir="data/indexes",
        processed_dir="data/processed",
    ):
        print("Initializing Telarc RAG pipeline...")

        self.index_dir = Path(index_dir)
        self.processed_dir = Path(processed_dir)

        # ---------------------------------------------------------
        # Vector store
        # ---------------------------------------------------------

        self.vector_store = VectorStore()
        self.vector_store.load(self.index_dir)

        # ---------------------------------------------------------
        # Financial lexical index
        #
        # This is loaded from the already-created processed JSON
        # files. No embeddings need to be rebuilt.
        # ---------------------------------------------------------

        self.financial_chunks = self._load_financial_chunks()

        self.generator = LocalGenerator()

        print(
            f"Financial chunks loaded: {len(self.financial_chunks)}"
        )

        print("Telarc RAG pipeline ready.")

    # =========================================================
    # QUESTION CLASSIFICATION
    # =========================================================

    def _is_financial_question(self, question: str) -> bool:

        question_lower = question.lower()

        return any(
            term in question_lower
            for term in FINANCIAL_TERMS
        )

    # =========================================================
    # COMPANY / DOCUMENT IDENTIFICATION
    # =========================================================

    def _identify_company(self, question: str) -> list[str]:

        question_lower = question.lower()

        companies = []

        if (
            "reliance jio" in question_lower
            or "jio" in question_lower
        ):
            companies.append("Reliance_Jio")

        if (
            "airtel" in question_lower
            or "bharti" in question_lower
        ):
            companies.append("Airtel")

        if "tata communications" in question_lower:
            companies.append("Tata")

        if (
            "vodafone idea" in question_lower
            or "vi " in question_lower
        ):
            companies.append("Vodafone")

        return companies

    # =========================================================
    # LOAD FINANCIAL CHUNKS
    # =========================================================

    def _load_financial_chunks(self) -> list[dict]:

        chunks = []

        if not self.processed_dir.exists():
            return chunks

        for json_file in sorted(
            self.processed_dir.glob("*.json")
        ):

            try:

                with json_file.open(
                    "r",
                    encoding="utf-8",
                ) as file:

                    document_chunks = json.load(file)

            except (OSError, json.JSONDecodeError):

                continue

            for chunk in document_chunks:

                # Financial chunks are generated by the
                # financial chunker and contain this metadata.
                #
                # We also allow financial-looking documents
                # to participate as a safety fallback.

                document_name = str(
                    chunk.get("document", "")
                ).lower()

                chunk_text = str(
                    chunk.get("text", "")
                )

                if (
                    "_financial_" in str(
                        chunk.get("chunk_id", "")
                    )
                    or "financial" in document_name
                    or self._looks_like_financial_chunk(
                        chunk_text
                    )
                ):
                    chunks.append(chunk)

        return chunks

    # =========================================================
    # FINANCIAL CHUNK DETECTION
    # =========================================================

    def _looks_like_financial_chunk(
        self,
        text: str,
    ) -> bool:

        text_lower = text.lower()

        indicators = (
            "revenue from operations",
            "total income",
            "profit before tax",
            "profit for the year",
            "statement of profit and loss",
            "balance sheet",
            "cash flow statement",
            "total assets",
            "total liabilities",
        )

        return any(
            indicator in text_lower
            for indicator in indicators
        )

    # =========================================================
    # EXTRACT SEARCH TERMS
    # =========================================================

    def _financial_search_terms(
        self,
        question: str,
    ) -> list[str]:

        question_lower = question.lower()

        terms = []

        # -----------------------------------------------------
        # Revenue
        # -----------------------------------------------------

        if "revenue" in question_lower:

            terms.extend(
                [
                    "revenue from operations",
                    "total income",
                    "statement of profit and loss",
                ]
            )

        # -----------------------------------------------------
        # Profit
        # -----------------------------------------------------

        if "profit" in question_lower:

            terms.extend(
                [
                    "profit for the year",
                    "profit before tax",
                    "statement of profit and loss",
                ]
            )

        # -----------------------------------------------------
        # Income
        # -----------------------------------------------------

        if "income" in question_lower:

            terms.extend(
                [
                    "total income",
                    "revenue from operations",
                ]
            )

        # -----------------------------------------------------
        # Expenses
        # -----------------------------------------------------

        if (
            "expense" in question_lower
            or "expenses" in question_lower
        ):

            terms.extend(
                [
                    "total expenses",
                    "statement of profit and loss",
                ]
            )

        # -----------------------------------------------------
        # Assets
        # -----------------------------------------------------

        if "asset" in question_lower:

            terms.extend(
                [
                    "total assets",
                    "balance sheet",
                ]
            )

        # -----------------------------------------------------
        # Liabilities
        # -----------------------------------------------------

        if "liabilit" in question_lower:

            terms.extend(
                [
                    "total liabilities",
                    "balance sheet",
                ]
            )

        # -----------------------------------------------------
        # Equity
        # -----------------------------------------------------

        if "equity" in question_lower:

            terms.extend(
                [
                    "total equity",
                    "balance sheet",
                ]
            )

        # -----------------------------------------------------
        # Cash flow
        # -----------------------------------------------------

        if (
            "cash flow" in question_lower
            or "cashflow" in question_lower
        ):

            terms.extend(
                [
                    "cash flow statement",
                    "operating activities",
                    "investing activities",
                    "financing activities",
                ]
            )

        # -----------------------------------------------------
        # Ratios
        # -----------------------------------------------------

        if "ratio" in question_lower:

            terms.extend(
                [
                    "financial ratios",
                    "ratio",
                ]
            )

        # Remove duplicates while preserving order.

        return list(dict.fromkeys(terms))

    # =========================================================
    # FINANCIAL LEXICAL RETRIEVAL
    # =========================================================

    def _financial_retrieve(
        self,
        question: str,
        limit: int = 8,
    ) -> list[dict]:

        if not self.financial_chunks:
            return []

        question_lower = question.lower()

        companies = self._identify_company(question)

        search_terms = self._financial_search_terms(
            question
        )

        matches = []

        for chunk in self.financial_chunks:

            text = str(
                chunk.get("text", "")
            )

            text_lower = text.lower()

            score = 0.0

            # -------------------------------------------------
            # Exact financial phrase matches
            # -------------------------------------------------

            for term in search_terms:

                if term in text_lower:

                    # Exact financial headings receive a
                    # strong deterministic boost.
                    if term == "revenue from operations":
                        score += 10.0

                    elif term == "profit for the year":
                        score += 10.0

                    elif term == "profit before tax":
                        score += 8.0

                    elif term == "statement of profit and loss":
                        score += 6.0

                    elif term == "total income":
                        score += 5.0

                    else:
                        score += 3.0

            # -------------------------------------------------
            # Company matching
            # -------------------------------------------------

            document_name = str(
                chunk.get("document", "")
            ).lower()

            chunk_id = str(
                chunk.get("chunk_id", "")
            ).lower()

            combined_identifier = (
                document_name
                + " "
                + chunk_id
            )

            if "reliance_jio" in combined_identifier:

                if "Reliance_Jio" in companies:
                    score += 15.0

            if (
                "bharti airtel" in combined_identifier
                or "airtel" in combined_identifier
            ):

                if "Airtel" in companies:
                    score += 15.0

            if (
                "tata" in combined_identifier
                and "communications" in combined_identifier
            ):

                if "Tata" in companies:
                    score += 15.0

            if (
                "vodafone" in combined_identifier
                or "idea" in combined_identifier
            ):

                if "Vodafone" in companies:
                    score += 15.0

            # -------------------------------------------------
            # Fiscal year matching
            # -------------------------------------------------

            year_patterns = re.findall(
                r"(?:fy\s*)?(20\d{2})[-–](\d{2,4})",
                question_lower,
            )

            for start_year, end_year in year_patterns:

                full_end_year = (
                    end_year
                    if len(end_year) == 4
                    else "20" + end_year
                )

                year_patterns_to_check = [
                    f"{start_year}-{end_year}",
                    f"{start_year}-{full_end_year}",
                    f"{start_year}–{end_year}",
                    f"{start_year}–{full_end_year}",
                ]

                if any(
                    year_pattern in text_lower
                    or year_pattern in document_name
                    for year_pattern in year_patterns_to_check
                ):
                    score += 8.0

            # -------------------------------------------------
            # Page 12 style statement headings
            # -------------------------------------------------

            if (
                "statement of profit and loss"
                in text_lower
            ):

                score += 4.0

            # -------------------------------------------------
            # Only retain chunks that actually match
            # something relevant.
            # -------------------------------------------------

            if score > 0:

                result = chunk.copy()

                # Keep lexical score separate from FAISS score.
                result["lexical_score"] = score

                # A deterministic retrieval result needs a
                # score field because the citation layer expects it.
                result["score"] = float(
                    score
                )

                matches.append(result)

        # Strongest exact matches first.

        matches.sort(
            key=lambda item: item["lexical_score"],
            reverse=True,
        )

        return matches[:limit]

    # =========================================================
    # NORMAL SEMANTIC QUERY EXPANSION
    # =========================================================

    def _build_search_queries(
        self,
        question: str,
    ) -> list[str]:

        queries = [question]

        if not self._is_financial_question(question):

            return queries

        question_lower = question.lower()

        # Revenue

        if "revenue" in question_lower:

            queries.extend(
                [
                    f"{question} revenue from operations",
                    f"{question} total income",
                    f"{question} statement of profit and loss",
                    f"{question} financial statements",
                ]
            )

        # Profit

        if "profit" in question_lower:

            queries.extend(
                [
                    f"{question} profit for the year",
                    f"{question} profit before tax",
                    f"{question} profit after tax",
                    f"{question} statement of profit and loss",
                ]
            )

        # Income

        if "income" in question_lower:

            queries.extend(
                [
                    f"{question} total income",
                    f"{question} revenue from operations",
                    f"{question} statement of profit and loss",
                ]
            )

        # Expenses

        if (
            "expense" in question_lower
            or "expenses" in question_lower
        ):

            queries.extend(
                [
                    f"{question} total expenses",
                    f"{question} statement of profit and loss",
                ]
            )

        # Assets / liabilities / equity

        if (
            "asset" in question_lower
            or "liabilit" in question_lower
            or "equity" in question_lower
        ):

            queries.extend(
                [
                    f"{question} balance sheet",
                    f"{question} total assets liabilities equity",
                ]
            )

        # Cash flow

        if (
            "cash flow" in question_lower
            or "cashflow" in question_lower
        ):

            queries.extend(
                [
                    f"{question} cash flow statement",
                    f"{question} operating investing financing cash flow",
                ]
            )

        # Ratios

        if "ratio" in question_lower:

            queries.extend(
                [
                    f"{question} financial ratios",
                    f"{question} ratio formulas",
                    f"{question} notes to financial statements",
                ]
            )

        return queries

    # =========================================================
    # SEMANTIC RETRIEVAL
    # =========================================================

    def _retrieve_semantic(
        self,
        question: str,
        top_k: int,
    ) -> list[dict]:

        search_queries = self._build_search_queries(
            question
        )

        all_results = []

        for query in search_queries:

            results = self.vector_store.search(
                query=query,
                top_k=top_k,
            )

            all_results.extend(results)

        # Remove duplicate chunks.

        unique_results = {}

        for result in all_results:

            chunk_id = result["chunk_id"]

            existing = unique_results.get(
                chunk_id
            )

            if existing is None:

                unique_results[chunk_id] = result

            elif result["score"] > existing["score"]:

                unique_results[chunk_id] = result

        results = list(
            unique_results.values()
        )

        results.sort(
            key=lambda item: item["score"],
            reverse=True,
        )

        return results[:top_k]

    # =========================================================
    # COMBINED RETRIEVAL
    # =========================================================

    def _retrieve(
        self,
        question: str,
        top_k: int,
    ) -> list[dict]:

        semantic_results = self._retrieve_semantic(
            question,
            top_k,
        )

        # -----------------------------------------------------
        # Financial questions get deterministic lexical
        # retrieval in addition to FAISS.
        # -----------------------------------------------------

        if self._is_financial_question(question):

            lexical_results = self._financial_retrieve(
                question,
                limit=8,
            )

            print(
                f"Financial retrieval: "
                f"{len(lexical_results)} exact matches"
            )

            combined = {}

            # Add semantic results.

            for result in semantic_results:

                chunk_id = result["chunk_id"]

                combined[chunk_id] = result.copy()

            # Add lexical results and allow their exact
            # retrieval score to dominate when appropriate.

            for result in lexical_results:

                chunk_id = result["chunk_id"]

                if chunk_id not in combined:

                    combined[chunk_id] = result.copy()

                else:

                    existing = combined[chunk_id]

                    lexical_score = result.get(
                        "lexical_score",
                        0.0,
                    )

                    # Preserve semantic score but add the
                    # deterministic lexical boost.

                    existing["score"] = float(
                        existing["score"]
                        + lexical_score
                    )

                    existing["lexical_score"] = (
                        lexical_score
                    )

            results = list(
                combined.values()
            )

            # Strongest evidence first.

            results.sort(
                key=lambda item: item["score"],
                reverse=True,
            )

            return results[:top_k]

        return semantic_results[:top_k]

    # =========================================================
    # BUILD LLM CONTEXT
    # =========================================================

    def build_context(
        self,
        results: list[dict],
    ) -> str:

        if not results:

            return ""

        evidence_blocks = []

        for source_id, result in enumerate(
            results,
            start=1,
        ):

            evidence_blocks.append(
                f"""
SOURCE [{source_id}]
Document: {result["document"]}
Page: {result["page"]}
Chunk ID: {result["chunk_id"]}

Evidence:
{result["text"]}
""".strip()
            )

        return "\n\n".join(
            evidence_blocks
        )

    # =========================================================
    # MAIN ANSWER METHOD
    # =========================================================

    def answer(
        self,
        question: str,
        top_k: int | None = None,
    ) -> dict:

        # -----------------------------------------------------
        # Choose retrieval depth
        # -----------------------------------------------------

        if top_k is None:

            if self._is_financial_question(
                question
            ):

                top_k = 12

            else:

                top_k = 7

        # -----------------------------------------------------
        # Retrieve evidence
        # -----------------------------------------------------

        results = self._retrieve(
            question=question,
            top_k=top_k,
        )

        # -----------------------------------------------------
        # Nothing retrieved
        # -----------------------------------------------------

        if not results:

            return {
                "question": question,
                "answer": ABSTAIN_MESSAGE,
                "answerable": False,
                "citations": [],
                "retrieved_chunks": [],
            }

        # -----------------------------------------------------
        # Build context
        # -----------------------------------------------------

        context = self.build_context(
            results
        )

        # -----------------------------------------------------
        # Grounded generation
        # -----------------------------------------------------

        generation = (
            self.generator.generate_structured(
                question=question,
                context=context,
            )
        )

        # -----------------------------------------------------
        # Model says evidence is insufficient
        # -----------------------------------------------------

        if not generation["answerable"]:

            return {
                "question": question,
                "answer": ABSTAIN_MESSAGE,
                "answerable": False,
                "citations": [],
                "retrieved_chunks": results,
            }

        # -----------------------------------------------------
        # Build citations
        # -----------------------------------------------------

        citations = build_citations(
            results
        )

        # -----------------------------------------------------
        # Keep only citations selected by Gemini
        # -----------------------------------------------------

        valid_source_ids = set(
            generation["source_ids"]
        )

        citations = [
            citation
            for citation in citations
            if citation["source_id"]
            in valid_source_ids
        ]

        # -----------------------------------------------------
        # Final response
        # -----------------------------------------------------

        return {
            "question": question,
            "answer": generation["answer"],
            "answerable": True,
            "citations": citations,
            "retrieved_chunks": results,
        }